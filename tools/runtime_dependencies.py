"""Bind installed venv bytes; not a hermetic OS/stdlib/shared-loader proof.

Caller must already own the bounded resource gate. No archive fallback for live
inputs. Source setup manifests describe installed bytes, not model correctness.
"""
import json
import os
from pathlib import Path
import re
import sys

from sparkle_provenance import archive, sha256


def require(value, message):
    if not value:
        raise RuntimeError(message)


def unique(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, 'duplicate manifest key: ' + key)
        result[key] = value
    return result


def child(root, name):
    require(isinstance(name, str) and name and not any(ord(c) < 32 for c in name), 'invalid path')
    value = Path(name)
    require(not value.is_absolute() and '..' not in value.parts, 'nonrelative manifest path')
    require(value.as_posix() == name, 'noncanonical manifest path')
    return root / value


def check_hash(path, expected):
    require(isinstance(expected, str) and re.fullmatch('[0-9a-f]{64}', expected), 'invalid SHA256')
    require(path.is_file(), 'missing dependency: ' + str(path))
    require(sha256(path) == expected, 'changed dependency: ' + str(path))
    require(archive(path) == expected, 'dependency changed during archive: ' + str(path))


def installed_inventory(venv):
    result = {}
    for path in sorted(venv.rglob('*')):
        require(path.suffix != '.pyc', 'preexisting/generated bytecode: ' + str(path))
        if path.is_dir():
            if path.is_symlink():
                # Default POSIX venv layout. No unbound alternate search trees.
                require(path == venv / 'lib64' and path.resolve() == (venv / 'lib').resolve(),
                        'unexpected directory symlink: ' + str(path))
            continue
        require(path.is_file(), 'unsupported/dangling dependency: ' + str(path))
        result[path.relative_to(venv.parent).as_posix()] = path
    return result


def dependency_snapshot(manifest_path, expected_manifest_sha256=None):
    manifest_path = Path(manifest_path).absolute()
    require(manifest_path.is_file() and not manifest_path.is_symlink(), 'invalid dependency manifest')
    digest = sha256(manifest_path)
    if expected_manifest_sha256 is not None:
        require(digest == expected_manifest_sha256, 'dependency manifest changed during suite')
    manifest = json.loads(manifest_path.read_text(), object_pairs_hook=unique)
    root = manifest_path.parent
    venv = root / 'venv'
    require(venv.is_dir() and not venv.is_symlink(), 'invalid venv directory')
    require(Path(sys.prefix).resolve() == venv.resolve(), 'qualifier is not running inside the bound venv')
    require(manifest['status'] == 'installed_bytes_bound_not_import_qualified', 'unsupported dependency manifest')
    python = manifest['python']
    require(Path(sys.executable).resolve() == Path(python['path']), 'Python executable differs')
    require(sys.version == python['version'], 'Python version differs')
    check_hash(Path(python['path']), python['sha256'])
    declared = manifest['installed_files']
    require(isinstance(declared, dict) and declared, 'empty dependency inventory')
    actual = installed_inventory(venv)
    require(set(actual) == set(declared), 'missing/extra installed files')
    for name, entry in declared.items():
        path = child(root, name)
        require(path == actual[name] and name.startswith('venv/'), 'installed path outside venv')
        require(set(entry) == {'sha256', 'symlink_target'}, 'unsupported installed-file metadata')
        target = str(path.resolve()) if path.is_symlink() else None
        require(target == entry['symlink_target'], 'dependency symlink target differs: ' + name)
        check_hash(path, entry['sha256'])
    evidence = manifest['evidence_sha256']
    require(isinstance(evidence, dict) and evidence, 'empty dependency evidence inventory')
    for name, expected in evidence.items():
        path = child(root, name)
        require(not path.is_symlink(), 'dependency evidence must not be symlinked')
        check_hash(path, expected)
    loader_names = {name for name in evidence if name.startswith('runtime-libs/')}
    if loader_names:
        require(loader_names == {'runtime-libs/libstdc++.so.6', 'runtime-libs/libgcc_s.so.1'},
                'unexpected explicit loader inventory')
        loader = root / 'runtime-libs'
        require(loader.is_dir() and not loader.is_symlink(), 'invalid explicit loader directory')
        require(os.environ.get('LD_LIBRARY_PATH') == str(loader), 'loader path differs from bound copies')
        require({path.name for path in loader.iterdir()} == {'libstdc++.so.6', 'libgcc_s.so.1'},
                'extra/missing explicit loader files')
        require({'loader-receipt.json', 'runtime-env.sh'} <= set(evidence), 'missing loader receipt')
    # Setup script bytes are historical generation inputs; require their direct
    # currently available copies too. This draft never resolves archive fallback.
    for name, expected in manifest['draft_scripts'].items():
        require(Path(name).is_absolute(), 'setup script path must be absolute')
        check_hash(Path(name), expected)
    check_hash(manifest_path, digest)
    return {'manifest': str(manifest_path), 'manifest_sha256': digest,
            'installed_file_count': len(actual),
            'distribution_versions': manifest['distribution_versions'],
            'explicit_loader_directory': str(root / 'runtime-libs') if loader_names else None,
            'scope': __doc__.strip()}
