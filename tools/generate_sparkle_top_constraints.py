def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    bounded_context()
    WORK.mkdir(parents=True, exist_ok=True)
    for path in WORK.iterdir():
        if path.is_file(): archive(path)
    summary = WORK / 'summary.json'
    summary.write_text(json.dumps({'status': 'incomplete', 'vivado_status': 'not_run'}) + '\n')
    driver = WORK / 'Owners.lean'
    inventory = WORK / 'owners.json'
    driver.write_text(ownership_driver(inventory))
    sources = [SOURCE, driver, Path(__file__).resolve(),
               ROOT / 'tools/sparkle_compiled_lean.py',
               ROOT / 'tools/sparkle_provenance.py',
               ROOT / 'tools/check_sparkle_fpga_top_complete.py',
               *[p for _, p in import_closure(driver).values()]]
    before = {str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p): archive(p) for p in sources}
    with (WORK / 'build.log').open('w') as log:
        subprocess.run(['lake', 'build', 'opentpu-gen'], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, check=True)
    run_generator(driver)
    owners = check_owners(json.loads(inventory.read_text()))
    target = WORK / 'otpu_top_native_sparkle.tcl'
    original = SOURCE.read_text()
    target.write_text(adapt(original))
    mock = mock_evaluate(SOURCE, target, WORK)
    # Bind the RAM owner to the independently qualified channel hierarchy too.
    qualification = ROOT / 'build/sparkle/formal_mem_channel/qualification.json'
    qualification_hash = archive(qualification)
    qualified = json.loads(qualification.read_text())
    require(qualified['status'] == 'passed', 'channel qualification missing')
    proof = qualified['bindings'][0]['local_proof']
    resolved = verify(proof['input_sha256'])
    hierarchy = ROOT / next(v for k, v in resolved.items() if k.endswith('/hierarchy.json'))
    modules = json.loads(hierarchy.read_text())['modules']
    xr = modules[modules['gate']['cells']['u_xr']['type']]
    require('mem' in xr['memories'], 'qualified XDMA FIFO memory owner differs')
    del modules, xr
    require(sha256(qualification) == qualification_hash, 'channel qualification changed during audit')
    require(all(sha256(ROOT / name) == digest for name, digest in before.items()), 'ownership sources changed')
    summary.write_text(json.dumps({'status': 'rtl_mapping_and_mock_passed', 'vivado_status': 'not_run',
      'scope': __doc__, 'owners': owners, 'mock_cases': mock,
      'input_sha256': before | {str(p.relative_to(ROOT)): archive(p) for p in
        [target, inventory, qualification, hierarchy]}}, indent=2) + '\n')


if __name__ == '__main__':
    main()
