"""Adapt only board temperature/I2C synchronizer ownership; never select a build.

Run through sparkle_bounded.py. AST ownership and mock Tcl checks do not establish
actual Vivado endpoint existence, CDC coverage, timing, or physical closure.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess

from check_sparkle_fpga_top_complete import bounded_context, require
from generate_sparkle_top_constraints import ownership_driver
from sparkle_compiled_lean import import_closure, run_generator
from sparkle_provenance import archive, sha256

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'boards/ypcb-00338/constraints/otpu_top_ld.xdc'
WORK = ROOT / 'build/sparkle/board_native_constraints'
MAPPING = {f'*u_board/{name}_reg*': f'*u_sys/impl/u_board/impl/u_signals/{name}_reg*'
           for name in ['tmp_s1', 'i2c_s1']}
HEADER = ('# Native synchronizer ownership adaptation; all other board policy unchanged.\n'
          '# Generated by tools/generate_sparkle_board_constraints.py.\n'
          '# PENDING: actual Vivado endpoint, CDC and timing qualification.\n')


def command(selector):
    return 'set_false_path -to [get_cells -hier -filter {NAME =~ ' + selector + '}]'


def adapt(source):
    result = source
    for old, new in MAPPING.items():
        require(source.splitlines().count(command(old)) == 1,
                f'expected exactly one original synchronizer command: {old}')
        require(source.count(old) == 1, f'unexpected extra selector occurrence: {old}')
        result = result.replace(command(old), command(new))
    generated = HEADER + result
    validate_adaptation(source, generated)
    return generated


def validate_adaptation(source, generated):
    require(generated.startswith(HEADER), 'missing qualification header')
    restored = generated[len(HEADER):]
    for old, new in MAPPING.items():
        require(restored.splitlines().count(command(new)) == 1,
                f'expected exactly one native synchronizer command: {new}')
        require(restored.count(new) == 1 and old not in restored,
                'extra or stale synchronizer selector')
        restored = restored.replace(command(new), command(old))
    require(restored == source, 'board pin/clock/GTX/LiteDRAM/policy changed')


def check_owners(data):
    require(dict(data['boundaries']).get('u_sys') == 'otpu_native_sys', 'wrong system boundary')
    wrappers = data['wrappers']
    require(len(wrappers) == 3, 'wrong ABI inventory')
    for text, kind in zip(wrappers[:2], ['otpu_native_sys_sparkle', 'otpu_board_sparkle']):
        require(len(re.findall(r'\b' + kind + r'\s+impl\s*\(', text)) == 1, 'wrong ABI impl owner')
    modules = {m['name']: m for m in data['modules']}
    require(len(modules) == len(data['modules']), 'duplicate module owner')
    for parent, child, kind in [('otpu_native_sys_sparkle', 'u_board', 'otpu_board'),
                                ('otpu_board_sparkle', 'u_signals', 'otpu_board_signals_sparkle')]:
        pairs = modules[parent]['instances']
        require(sum(n == child for n, _ in pairs) == 1 and dict(pairs)[child] == kind,
                f'wrong native owner: {parent}/{child}')
    regs = modules['otpu_board_signals_sparkle']['registers']
    for name in ['tmp_s1', 'i2c_s1']:
        require(regs.count(name) == 1, f'wrong synchronizer owner: {name}')
    return {'tmp_s1': 'u_sys/impl/u_board/impl/u_signals/tmp_s1',
            'i2c_s1': 'u_sys/impl/u_board/impl/u_signals/i2c_s1'}


MOCK = r'''
set native @NATIVE@
set events {}
proc get_ports {args} {return [lindex $args end]}
proc current_design {} {return otpu_fpga_top_ld}
proc get_cells {args} {
  if {[llength $args] == 1} {
    set name [lindex $args 0]
    if {$name ni {u_ld/ldmmcm0 u_ld/ldmmcm1}} {error "unexpected direct cell: $name"}
    return $name
  }
  if {[lrange $args 0 1] ne {-hier -filter}} {error "unexpected cell query: $args"}
  set clause [lindex $args end]
  if {![regexp {^NAME =~ (.+)$} $clause -> pattern]} {error "unexpected filter: $clause"}
  set owner [expr {$::native ? "u_sys/impl/u_board/impl/u_signals" : "u_sys/u_board"}]
  set cells {}
  foreach {name width} {tmp_s1 12 i2c_s1 5} {
    for {set i 0} {$i < $width} {incr i} {lappend cells "$owner/${name}_reg$i"}
  }
  for {set i 0} {$i < 8} {incr i} {
    lappend cells "u_bd/xdma/pipe_lane\[$i\].gt_wrapper_i/gtx_channel.gtxe2_channel_i"
  }
  set selected [lsearch -all -inline -glob $cells $pattern]
  if {[llength $selected] == 0} {error "empty endpoint query: $pattern"}
  return $selected
}
proc set_property {args} {lappend ::events [linsert $args 0 set_property]}
proc create_clock {args} {lappend ::events [linsert $args 0 create_clock]}
proc set_false_path {args} {lappend ::events [linsert $args 0 set_false_path]}
'''


def mock_evaluate(source, generated, directory):
    traces = []
    for native, path in [(False, source), (True, generated)]:
        script = directory / f'board-mock-{int(native)}.tcl'
        script.write_text(MOCK.replace('@NATIVE@', str(int(native))) + '\nsource {' + str(path) +
                          '}\nforeach event $events {puts "EVENT:$event"}\n')
        result = subprocess.run(['tclsh', str(script)], text=True, capture_output=True, check=True)
        script.with_suffix('.log').write_text(result.stdout + result.stderr)
        events = [s[6:] for s in result.stdout.splitlines() if s.startswith('EVENT:')]
        require(len(events) == 43, f'board command inventory changed: {len(events)}')
        traces.append([s.replace('u_sys/impl/u_board/impl/u_signals/', 'u_sys/u_board/')
                       for s in events] if native else events)
    require(traces[0] == traces[1], 'mock selected endpoints or board commands differ')
    return {'commands': len(traces[0]), 'temperature_endpoints': 12, 'i2c_endpoints': 5,
            'gtx_endpoints': 8, 'litedram_mmcm_endpoints': 2}


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    bounded_context()
    WORK.mkdir(parents=True, exist_ok=True)
    for p in WORK.iterdir():
        if p.is_file(): archive(p)
    summary = WORK / 'summary.json'
    summary.write_text(json.dumps({'status': 'incomplete', 'vivado_status': 'not_run'}) + '\n')
    driver, inventory = WORK / 'Owners.lean', WORK / 'owners.json'
    driver.write_text(ownership_driver(inventory))
    sources = [SOURCE, driver, Path(__file__).resolve(),
               ROOT / 'tools/generate_sparkle_top_constraints.py',
               ROOT / 'tools/check_sparkle_fpga_top_complete.py',
               ROOT / 'tools/sparkle_compiled_lean.py', ROOT / 'tools/sparkle_provenance.py',
               *[p for _, p in import_closure(driver).values()]]
    before = {str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p): archive(p)
              for p in sources}
    with (WORK / 'build.log').open('w') as log:
        subprocess.run(['lake', 'build', 'opentpu-gen'], cwd=ROOT, stdout=log,
                       stderr=subprocess.STDOUT, check=True)
    run_generator(driver)
    owners = check_owners(json.loads(inventory.read_text()))
    target = WORK / 'otpu_top_ld_sparkle.xdc'
    target.write_text(adapt(SOURCE.read_text()))
    mock = mock_evaluate(SOURCE, target, WORK)
    require(all(sha256(ROOT / p) == digest for p, digest in before.items()), 'audit input changed')
    summary.write_text(json.dumps({'status': 'rtl_mapping_and_mock_passed', 'vivado_status': 'not_run',
      'scope': __doc__, 'owners': owners, 'mock': mock,
      'input_sha256': before, 'output_sha256': {str(p.relative_to(ROOT)): archive(p)
         for p in [target, inventory, driver.with_suffix('.runner.json')]}}, indent=2) + '\n')


if __name__ == '__main__':
    main()
