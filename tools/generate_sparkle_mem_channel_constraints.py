"""Map the existing CDC constraints onto the native channel's explicit hierarchy.

This checks RTL endpoint ownership against the qualified hierarchy. Vivado must
still confirm post-synthesis cell names, complete crossing coverage and timing.
The original board constraints and build selection are deliberately unchanged.
"""
import fnmatch,json,re,subprocess
from pathlib import Path
from sparkle_provenance import archive,verify
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'boards/ypcb-00338/constraints/otpu_mem_ch.tcl'
TARGET=ROOT/'boards/ypcb-00338/constraints/otpu_mem_ch_sparkle.tcl'
WORK=ROOT/'build/sparkle/mem_channel_constraints'
OWNERS={
    'u_reset':['a_rs1','x_rs1','a_hs1','x_hs1'],
    'u_accelerator':['e_s1','a_wacc_s1','n_rdata'],
    'u_xdma':['x_wacc_s1'],
    'u_controller':['a_wacc_g','x_wacc_g','run','cur_x','rm_busy','rm_x',
                    'a_out','x_out','a_pend','x_pend','a_seq','x_seq','a_nq','x_nq'],
}
FIFOS=['aq','ad','ar','xq','xd','xr']


def generate(source):
    lines=[]
    for line in source.splitlines():
        if line.lstrip().startswith('#'):
            lines.append(line);continue
        # The original generate block becomes explicit native instances/registers.
        for old,new in [('u_oq','u_oq'),('u_of','u_of'),('u_tag','u_tg')]:
            line=line.replace(f'g_port[*].{old}/wp_reg*',
                f'impl/{new}0/wp_reg* impl/{new}1/wp_reg*')
            line=line.replace(f'*{old}/mem_reg*',f'*impl/{new}*/mem_reg*')
        for old,new in [('oc_reg[*]','oc'),('oc_v_reg','oc_v')]:
            tail='[*]' if old.endswith('[*]') else ''
            line=line.replace(f'g_port[*].{old}',
                ' '.join(f'impl/u_controller/{new}{i}_reg{tail}' for i in range(2)))
        for owner,names in OWNERS.items():
            for name in names:
                line=re.sub(r'(?<![\w/])'+name+r'_reg\b',f'impl/{owner}/{name}_reg',line)
        line=re.sub(r'(?<![\w/])u_('+'|'.join(FIFOS)+r')\b',r'impl/u_\1',line)
        assert 'g_port[' not in line,line
        lines.append(line)
    return ('# Native Sparkle hierarchy adaptation; generated by tools/generate_sparkle_mem_channel_constraints.py.\n'
      '# Scope remains otpu_mem_ch (the native ABI). Post-synthesis endpoint validation is REQUIRED.\n'
      '# RTL ownership checks do not establish Vivado naming, CDC classification or timing closure.\n'
      +'\n'.join(lines)+'\n')


def audit(proof):
    resolved=verify(proof['input_sha256'])
    path=ROOT/next(v for k,v in resolved.items() if k.endswith('/hierarchy.json'))
    modules=json.loads(path.read_text())['modules'];top=modules['gate'];checked=[]
    def instance(name):return modules[top['cells'][name]['type']]
    for owner,names in OWNERS.items():
        m=instance(owner)
        q={b for c in m['cells'].values() if 'dff' in c['type'].lower() for b in c['connections']['Q']}
        for name in names:
            assert name in m['netnames'],(owner,name)
            bits=m['netnames'][name]['bits'];assert set(bits)<=q,(owner,name,'not registered')
            checked.append({'instance':'impl/'+owner,'register':name,'bits':len(bits)})
    for f in FIFOS:
        m=instance('u_'+f)
        for n in ['wgray','wbin','wgray_r1','rgray','rbin','rgray_w1']:
            assert n in m['netnames'],(f,n)
        assert 'mem' in m['memories'],f
    for p in range(2):
        for f in ['oq','of','tg']:
            m=instance(f'u_{f}{p}');assert 'wp' in m['netnames'] and 'mem' in m['memories']
        for n in [f'oc{p}',f'oc_v{p}']:assert n in instance('u_controller')['netnames']
    return {'config':proof['config'],'register_ownership':checked,'async_fifos':6,
            'output_fifos':6,'hierarchy_sha256':archive(path)}


def tcl_evaluate():
    setup='''proc get_ports {args} {return [lindex $args end]}
proc get_clocks {args} {return [lindex $args end]}
proc get_property {args} {return 8.0}
proc get_cells {args} {puts "CELL_QUERY:[join $args {|}]"; return mock_cell}
proc get_pins {args} {puts "PIN_QUERY:[join $args {|}]"; return mock_pin}
set md 0; set skew 0; set waiver 0
proc set_max_delay {args} {incr ::md}
proc set_bus_skew {args} {incr ::skew}
proc create_waiver {args} {incr ::waiver}
'''
    records=[]
    for path in [SOURCE,TARGET]:
        script=WORK/(path.stem+'_syntax.tcl');log=WORK/(path.stem+'_syntax.log')
        script.write_text(setup+'source {'+str(path)+'}\nputs "COUNTS:$md,$skew,$waiver"\n')
        result=subprocess.run(['yosys','-Q','-T','-c',str(script)],capture_output=True,text=True,check=True)
        log.write_text(result.stdout+result.stderr)
        counts=next(line for line in result.stdout.splitlines() if line.startswith('COUNTS:'))
        queries=[line for line in result.stdout.splitlines() if '_QUERY:' in line]
        if path==TARGET:
            assert all('g_port' not in line and 'u_tag/' not in line for line in queries)
        records.append({'name':path.stem,'counts':counts,'queries':len(queries),
                        'script_sha256':archive(script),'log_sha256':archive(log)})
    assert records[0]['counts']==records[1]['counts']
    assert records[0]['queries']==records[1]['queries']
    return {'status':'passed','scope':'Tcl syntax and command counts with mock Vivado queries; not synthesis endpoint validation',
            'results':records}


def check_projected_queries(proof, text):
    resolved=verify(proof['input_sha256'])
    path=ROOT/next(v for k,v in resolved.items() if k.endswith('/hierarchy.json'))
    modules=json.loads(path.read_text())['modules'];top=modules['gate']
    queries=set(re.findall(r'impl/(u_\w+\*?)/(\w+)_reg',text))
    assert queries
    for pattern,name in queries:
        instances=[n for n in top['cells'] if fnmatch.fnmatchcase(n,pattern)]
        assert instances,('unknown native instance',pattern)
        for instance in instances:
            m=modules[top['cells'][instance]['type']]
            if name=='mem':assert name in m.get('memories',{}),(instance,name)
            else:
                q={b for cell in m['cells'].values() if 'dff' in cell['type'].lower()
                   for b in cell['connections']['Q']}
                assert name in m['netnames'] and set(m['netnames'][name]['bits'])<=q,(instance,name)
    return len(queries)


def main():
    qpath=ROOT/'build/sparkle/formal_mem_channel/qualification.json'
    q=json.loads(qpath.read_text());assert q['status']=='passed'
    records=[audit(b['local_proof']) for b in q['bindings']]
    original=SOURCE.read_text();generated=generate(original)
    for command in ['set_max_delay','set_bus_skew','create_waiver']:
        assert len(re.findall(r'^\s*'+command+r'\b',original,re.M))==len(re.findall(r'^\s*'+command+r'\b',generated,re.M))
    if TARGET.exists():archive(TARGET)
    TARGET.write_text(generated)
    WORK.mkdir(parents=True,exist_ok=True)
    syntax=tcl_evaluate()
    queries=(WORK/(TARGET.stem+'_syntax.log')).read_text()
    projected=[check_projected_queries(b['local_proof'],queries) for b in q['bindings']]
    broken=queries.replace('impl/u_accelerator/a_wacc_s1_reg','impl/u_xdma/a_wacc_s1_reg')
    assert broken!=queries
    try:check_projected_queries(q['bindings'][0]['local_proof'],broken)
    except AssertionError:pass
    else:raise AssertionError('misdirected synchronizer query was accepted')
    (WORK/'summary.json').write_text(json.dumps({'status':'rtl_mapping_passed',
      'vivado_status':'not_run','scope':__doc__,'cases':records,'tcl_evaluation':syntax,
      'projected_query_counts':projected,'wrong_synchronizer_owner_mutation_rejected':True,
      'input_sha256':{str(p.relative_to(ROOT)):archive(p) for p in [SOURCE,TARGET,qpath,Path(__file__).resolve()]}},indent=2)+'\n')
    print('Native CDC constraint RTL mapping passed for',len(records),'configurations; Vivado validation remains required')
if __name__=='__main__':main()
